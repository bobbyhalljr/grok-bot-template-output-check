import test from 'node:test';
import assert from 'node:assert/strict';
import { validateBrief } from './brief.ts';
import { contract, fixture } from './fixtures.ts';
const check = (mutate: (b: any) => void, status = 'invalid') => {
  const b = fixture(); mutate(b); assert.equal(validateBrief(b, contract).status, status);
};
test('valid example is review-ready',()=>check(()=>{},'ready'));
test('checked empty result is ready',()=>check(b=>b.items=[],'ready'));
test('empty unchecked result is partial',()=>check(b=>{b.items=[];b.coverage[0]={source:contract.requiredSources[0],state:'unavailable'}},'partial'));
test('partial preserves validated items from available sources',()=>check(b=>b.coverage[0]={source:contract.requiredSources[0],state:'unavailable'},'partial'));
test('omitted source is invalid',()=>check(b=>b.coverage.pop()));
test('duplicate source is invalid',()=>check(b=>b.coverage.push(b.coverage[0])));
test('undeclared source is invalid',()=>check(b=>b.coverage[0].source='https://other.example.com'));
test('stale checked-at is invalid',()=>check(b=>b.coverage[0].checkedAt='2026-10-26T00:00:00Z'));
test('checked-at without timezone is invalid',()=>check(b=>b.coverage[0].checkedAt='2026-10-27T01:00:00'));
test('coverage state is explicit',()=>check(b=>b.coverage[0].state='probably'));
test('published delivery is rejected',()=>check(b=>b.delivery='published'));
test('overflow is rejected without silently trimming',()=>check(b=>b.items=Array.from({length:contract.maxItems+1},(_,i)=>({...b.items[0],id:String(i)}))));
test('duplicate item id is rejected',()=>check(b=>b.items.push({...b.items[0]})));
test('empty title is rejected',()=>check(b=>b.items[0].title='  '));
test('empty item id is rejected',()=>check(b=>b.items[0].id=''));
test('unknown kind is rejected',()=>check(b=>b.items[0].kind='maybe'));
test('before-window item is rejected',()=>check(b=>b.items[0].occurredAt='2026-10-19T00:00:00Z'));
test('after-window item is rejected',()=>check(b=>b.items[0].occurredAt='2026-10-28T00:00:00Z'));
test('window boundaries are inclusive',()=>{for(const t of [contract.start,contract.end])check(b=>b.items[0].occurredAt=t,'ready')});
test('javascript evidence is rejected',()=>check(b=>b.items[0].source='javascript:alert(1)'));
test('URL credentials are rejected',()=>check(b=>b.items[0].source='https://user:pass@releases.example.com'));
test('evidence from an unchecked origin is rejected',()=>check(b=>b.coverage[1]={source:contract.requiredSources[1],state:'unavailable'}));
test('evidence from an undeclared origin is rejected',()=>check(b=>b.items[0].source='https://unlisted.example.com/a'));
test('malformed runtime input is rejected',()=>{for(const b of [null,[],{}, {items:[],coverage:null}])assert.equal(validateBrief(b,contract).status,'invalid')});
test('invalid contracts are rejected',()=>{for(const c of [{...contract,maxItems:0},{...contract,start:contract.end,end:contract.start},{...contract,requiredSources:[]},{...contract,requiredSources:['no-url']}])assert.equal(validateBrief(fixture(),c).status,'invalid')});
